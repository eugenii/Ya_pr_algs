# Для поиска минимального количества правок (вставка, удаление, замена) 
# используется метод двумерного динамического программирования (алгоритм Вагнера — Фишера).
# Задача обладает свойством оптимальной подструктуры: расстояние между строками длины i и j можно эффективно вычислить,
# зная расстояния между их префиксами. Мы строим матрицу dp размером (N+1) * (M+1), 
# где dp[i][j] означает минимальное количество операций для перевода префикса строки S длины i 
# в префикс строки T длины j.
# Базовые случаи: Конвертация пустой строки в строку длины K требует ровно K вставок 
# (первая строка и первый столбец заполняются индексами).
# Шаг ДП: Если текущие символы совпадают (S[i-1] == T[j-1]), операция не требуется: dp[i][j] = dp[i-1][j-1]. 
# Если символы различаются, мы выбираем минимум из трёх возможных предыдущих состояний (удаление, вставка, замена) 
# и добавляем стоимость текущей операции \((+1)\):
# dp[i][j]=1+min (dp[i-1][j], dp[i][j-1], dp[i-1][j-1])
# Асимптотика
# Временная сложность (Time Complexity): 
# O(N * M)\), где N — длина первой строки, а M — длина второй строки. 
# Мы используем два вложенных цикла, каждый из которых выполняет константное число операций O(1) для каждой клетки матрицы. 
# При ограничениях (N, M < 1000) алгоритм выполняет порядка 10^6 операций, что мгновенно отрабатывает в лимитах времени.
# Пространственная сложность (Space Complexity): 
# O(N * M) для хранения двумерного массива состояний размера (N+1) * (M+1). 
# При (N, M = 1000) матрица занимает около 10^6 элементов типа int, что требует всего несколько мегабайт памяти 
# и легко проходит ограничения по памяти.

s, t = input(), input()

dp = [[0] * (len(t) + 1) for _ in range(len(s) + 1)]

for i in range(len(s) + 1):
    dp[i][0] = i

for j in range(len(t) + 1):
    dp[0][j] = j

for i in range(1, len(s) + 1):
    for j in range(1, len(t) + 1):
        if s[i - 1] == t[j - 1]:
            # Буквы совпали — стоимость операции 0, берём значение по диагонали
            dp[i][j] = dp[i - 1][j - 1]
        else:
            # Буквы разные — выбираем минимальный путь из трёх соседей и добавляем 1
            dp[i][j] = 1 + min(
                dp[i - 1][j],     # Удаление
                dp[i][j - 1],     # Вставка
                dp[i - 1][j - 1]  # Замена
            )

print(dp[len(s)][len(t)])
