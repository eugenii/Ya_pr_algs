# B Калькулятор (польская нотация).
# Ссылка на успешное решение: https://contest.yandex.ru/contest/22781/run-report/157097940/
# Для реализации используется стек.
# Команды калькулятора записаны в словарь, при вызове передаются аргументы в lambda-функцию
# Операнды забираются  с вершины стека.
# При  достижении конца строки выводится результат. Как показала ошибка в тренажёре - необходим последний элемент.
# При вычислении сначала берётся второй операнд, затем первый.
# 
# Асимптотическая сложность:

# По времени: O(N), где N — количество токенов (чисел и операций) во входной строке.
# Обоснование: Алгоритм выполняет один проход по входным данным. Для каждого токена 
# выполняется ровно одна операция:
# Если токен — число, оно помещается в стек (операция O(1)).
# Если токен — оператор, из стека извлекаются два верхних элемента (дважды O(1)), 
# выполняется арифметическая операция (O(1)), и результат помещается обратно в стек 
# (O(1)).
# Так как каждый из N токенов обрабатывается за константное время, общая временная 
# сложность составляет O(N).
# 
# По памяти: O(N).
# Обоснование: В худшем случае (например, выражение состоит только из чисел, за 
# которыми следует оператор) размер стека может достигать N. Также мы храним входной 
# массив данных data размером N. Таким образом, затраты памяти линейно зависят от 
# длины входной строки.

stack = []

data = input().split()

commands = {
    "+": lambda x, y: x + y,
    "-": lambda x, y: x - y,
    "*": lambda x, y: x * y,
    "/": lambda x, y: int(x / y),
}

for i in range(len(data)):
    if data[i] in commands:
        y = stack.pop()
        x = stack.pop()
        stack.append(commands[data[i]](x, y))
    else:
        stack.append(int(data[i]))
print(stack[0])
